// Regenerates skill-icons.js from the `icon` slugs used in content.js.
//
//   npm i --no-save simple-icons
//   node tools/build-icons.mjs
//
// Only the path data is copied — no brand colours — so the page can paint
// every logo in its own ink. Simple Icons is CC0-1.0. A slug that Simple
// Icons doesn't have is reported and left out; the page shows that skill
// as a plain text pill instead.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const from = process.env.SIMPLE_ICONS_DIR || root;
const require = createRequire(path.join(from, 'noop.js'));
const si = require('simple-icons');
/* package.json isn't in the package's exports map, so read it off disk */
let dir = path.dirname(require.resolve('simple-icons'));
while (!existsSync(path.join(dir, 'package.json'))) dir = path.dirname(dir);
const { version } = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(path.join(root, 'content.js'), 'utf8'), sandbox);
const slugs = [...new Set(sandbox.window.CONTENT.skills.groups
  .flatMap(g => g.items).map(s => s.icon).filter(Boolean))];

const bySlug = {};
for (const icon of Object.values(si)) if (icon && icon.slug) bySlug[icon.slug] = icon;

const out = {}, missing = [];
for (const slug of slugs) {
  const icon = bySlug[slug];
  if (icon) out[slug] = { title: icon.title, path: icon.path };
  else missing.push(slug);
}

writeFileSync(path.join(root, 'skill-icons.js'),
`/* Logo paths from Simple Icons ${version} (https://simpleicons.org, CC0-1.0).
 * Generated by tools/build-icons.mjs from the slugs in content.js — edit
 * content.js and rerun the script rather than editing this file. */
window.SKILL_ICONS = ${JSON.stringify(out, null, 2)};
`);

console.log(`skill-icons.js: ${Object.keys(out).length} icons from simple-icons ${version}`);
if (missing.length) console.log('not in Simple Icons (shown as pills):', missing.join(', '));
